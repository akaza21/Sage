use serde::{Deserialize, Serialize};

use crate::acp::{
    intent::NormalizedPayload,
    lifecycle::{ItemLifecycle, ToolState},
};

/// The pinned Codex release. Every version-bearing identity in the binding is
/// derived from this and the schema prefix below. A version bump still
/// changes the pinned facts held in:
/// - this module (the schema digest);
/// - the binding's `manifest` and `pinned_artifacts` (package metadata,
///   commit, artifact hashes and Authenticode classes);
/// - `admission` (`BINDING_DIGEST` and `BINDING_DIGEST_HEX`);
/// - `reproduction` (`TARBALL_SHA512_HEX`, `NPM_SIGNATURE`, `NPM_KEY_ID` and
///   `OPENAI_THUMBPRINT`);
/// - the Codex fixtures under `testdata/acp/codex` and the recorded harness
///   traces under `tests/fixtures/harness-traces/codex`.
macro_rules! pinned_codex_version {
    () => {
        "0.167.0"
    };
}
pub(crate) use pinned_codex_version;

/// SHA-256 of `codex_app_server_protocol.schemas.json` as generated by the
/// pinned release's `codex app-server generate-json-schema --experimental`.
macro_rules! pinned_schema_sha256 {
    () => {
        "486c7c8daa5dc7f3ab2a1fb56de5316804caf7a4210fda1dc28d3f0f4e90cfe1"
    };
}
pub(crate) use pinned_schema_sha256;

/// The first eight hex digits of `pinned_schema_sha256!`.
macro_rules! pinned_schema_prefix {
    () => {
        "486c7c8d"
    };
}
pub(crate) use pinned_schema_prefix;

pub(crate) const PINNED_CODEX_VERSION: &str = pinned_codex_version!();
pub(crate) const PINNED_PROTOCOL_IDENTITY: &str = concat!(
    "codex-app-server-",
    pinned_codex_version!(),
    "-",
    pinned_schema_prefix!()
);
/// A user-installed Codex of exactly the pinned version, admitted by its
/// characterised wire rather than by the curated packet.
pub(crate) const OBSERVED_PROTOCOL_IDENTITY: &str =
    concat!("codex-app-server-observed-", pinned_codex_version!());

pub(crate) fn speaks_pinned_protocol(identity: &str) -> bool {
    matches!(
        identity,
        PINNED_PROTOCOL_IDENTITY | OBSERVED_PROTOCOL_IDENTITY
    )
}

pub(crate) const MAX_SNAPSHOT_BYTES: usize = 4_194_304;
pub(crate) const MAX_TURNS: usize = 128;
pub(crate) const MAX_ITEMS: usize = 1024;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub(crate) struct ChildTranscriptSnapshot {
    pub(crate) child_thread_id: String,
    pub(crate) parent_thread_id: String,
    pub(crate) turns: Vec<ChildTurn>,
    #[serde(default)]
    pub(crate) retention_limited: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub(crate) struct ChildTurn {
    pub(crate) id: String,
    pub(crate) status: String,
    pub(crate) items: Vec<ChildItem>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub(crate) struct ChildItem {
    pub(crate) id: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub(crate) role: Option<ChildTextRole>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub(crate) observed_sequence: Option<u64>,
    pub(crate) lifecycle: ItemLifecycle,
    pub(crate) tool_state: Option<ToolState>,
    pub(crate) payload: NormalizedPayload,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub(crate) enum ChildTextRole {
    User,
    Assistant,
}

impl ChildTranscriptSnapshot {
    pub(crate) fn within_bounds(&self) -> bool {
        self.turns.len() <= MAX_TURNS
            && self
                .turns
                .iter()
                .map(|turn| turn.items.len())
                .sum::<usize>()
                <= MAX_ITEMS
            && serde_json::to_vec(self).is_ok_and(|bytes| bytes.len() <= MAX_SNAPSHOT_BYTES)
    }
}
